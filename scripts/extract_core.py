#!/usr/bin/env python3
"""Extract only marked executable bodies from the Verus source. --check detects drift.

This small generator and the Rust/Verus compilers are part of the trusted boundary.
No handwritten alternative implementation is permitted in crates/cairn-verified/src/lib.rs.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SIGNATURES = {
    "normalize_key": "pub fn normalize_key(key: i64) -> u64",
    "shard_for_key": "pub fn shard_for_key(key: i64, count: u64) -> u64",
    "valid_frame": "pub fn valid_frame(length: u32, maximum: u32) -> bool",
    "payload_length": "pub fn payload_length(length: u32, _maximum: u32) -> u32",
    "accepts_topology": "pub fn accepts_topology(actual_id: u64, actual_count: u64, expected_id: u64, expected_count: u64) -> bool",
    "accepts_leader": "pub fn accepts_leader(writable: bool, term: u64, minimum_term: u64) -> bool",
    "may_decide_commit": "pub fn may_decide_commit(prepared: u64, participants: u64, aborted: bool) -> bool",
    "transaction_home": "pub fn transaction_home(prefix: u16, scoped: bool) -> u64",
    "checked_add_i64": "pub fn checked_add_i64(a: i64, b: i64) -> Option<i64>",
    "checked_sub_i64": "pub fn checked_sub_i64(a: i64, b: i64) -> Option<i64>",
    "may_commit_locally": "pub fn may_commit_locally(participants: u64, coordinator: u64, participant: u64) -> bool",
    "valid_read_batch": "pub fn valid_read_batch(requests: u64, responses: u64, maximum: u64) -> bool",
    "next_incarnation": "pub fn next_incarnation(current: u64) -> Option<u64>",
    "may_use_open_state": "pub fn may_use_open_state(present: bool, current: u64, stored: u64, requested: u64) -> bool",
}
source = (ROOT / "crates/cairn-verified/verify.rs").read_text()
blocks = re.findall(r"// runtime-begin (\w+)\n(.*?)\n// runtime-end", source, re.S)
assert [name for name, _ in blocks] == list(SIGNATURES), "unexpected runtime blocks"
result = "// Generated by scripts/extract_core.py from crates/cairn-verified/verify.rs. Do not edit.\n\n"
result += "\n\n".join(SIGNATURES[name] + " " + body for name, body in blocks) + "\n"
destination = ROOT / "crates/cairn-verified/src/lib.rs"
if "--check" in sys.argv:
    if not destination.exists() or destination.read_text() != result:
        sys.exit("crates/cairn-verified/src/lib.rs differs from the executable Verus source; run scripts/extract_core.py")
else:
    destination.write_text(result)
